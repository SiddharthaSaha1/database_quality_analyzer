-- ==============================================================================
-- AI-Based Database Data-Quality Analyzer
-- ORACLE AUDIT LOG & ANOMALY RESULTS TABLES
-- ==============================================================================

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE AUDIT_LOG CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE CONSOLIDATED_ANOMALIES CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- TABLE: AUDIT_LOG (Stores Rule-based SQL & PL/SQL findings)
CREATE TABLE AUDIT_LOG (
    ISSUE_ID            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RECORD_ID           VARCHAR2(50),
    TABLE_NAME          VARCHAR2(50),
    COLUMN_NAME         VARCHAR2(50),
    ISSUE_TYPE          VARCHAR2(50),       -- 'NULL_VALUE', 'DUPLICATE', 'OUT_OF_RANGE', 'INCONSISTENCY', 'FORMAT_ERROR'
    DESCRIPTION         VARCHAR2(500),
    SEVERITY            VARCHAR2(20),       -- 'HIGH', 'MEDIUM', 'LOW'
    DETECTION_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP,
    DETECTION_SOURCE    VARCHAR2(50)        -- 'SQL_RULE_ENGINE', 'PLSQL_PROCEDURE', etc.
);

-- TABLE: CONSOLIDATED_ANOMALIES (Stores Hybrid SQL + ML Consolidated results)
CREATE TABLE CONSOLIDATED_ANOMALIES (
    ANOMALY_ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RECORD_ID           VARCHAR2(50) NOT NULL,
    TABLE_NAME          VARCHAR2(50) NOT NULL,
    DETECTION_METHOD    VARCHAR2(100),      -- 'SQL_RULES', 'ISOLATION_FOREST', 'DBSCAN', 'HYBRID_SQL_ML'
    ISSUE_CATEGORY      VARCHAR2(100),      -- 'LOGICAL_INCONSISTENCY', 'STATISTICAL_OUTLIER', 'FORMAT_DEFECT', etc.
    EXPLANATION         VARCHAR2(1000),     -- Clear, evidence-based reason why flagged
    SEVERITY            VARCHAR2(20),       -- 'HIGH', 'MEDIUM', 'LOW'
    RELEVANT_COLUMN     VARCHAR2(100),
    ORIGINAL_VALUES     VARCHAR2(4000),     -- JSON string or key=val summary of row attributes
    ANOMALY_SCORE       NUMBER(8,4),        -- Normalized ML anomaly score (e.g. 0.0 to 1.0) or NULL
    DETECTION_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Performance indices for reporting queries
CREATE INDEX IDX_AUDIT_LOG_TABLE ON AUDIT_LOG (TABLE_NAME);
CREATE INDEX IDX_AUDIT_LOG_SEVERITY ON AUDIT_LOG (SEVERITY);
CREATE INDEX IDX_CONSOL_ANOM_SEV ON CONSOLIDATED_ANOMALIES (SEVERITY);
CREATE INDEX IDX_CONSOL_ANOM_METHOD ON CONSOLIDATED_ANOMALIES (DETECTION_METHOD);

