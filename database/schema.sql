-- TABLE 1: STUDENT
CREATE TABLE STUDENT (
    STUDENT_ID       VARCHAR2(20) NOT NULL,
    STUDENT_NAME     VARCHAR2(100),
    AGE              NUMBER(3),
    GENDER           VARCHAR2(10),
    DEPARTMENT       VARCHAR2(50),
    YEAR_OF_STUDY    NUMBER(1),
    EMAIL            VARCHAR2(100),
    PHONE_NUMBER     VARCHAR2(20),
    CONSTRAINT PK_STUDENT PRIMARY KEY (STUDENT_ID)
);

-- TABLE 2: COURSE
CREATE TABLE COURSE (
    COURSE_ID        VARCHAR2(20) NOT NULL,
    COURSE_NAME      VARCHAR2(100) NOT NULL,
    DEPARTMENT       VARCHAR2(50),
    CREDITS          NUMBER(2),
    CONSTRAINT PK_COURSE PRIMARY KEY (COURSE_ID)
);

-- TABLE 3: ATTENDANCE
CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID         VARCHAR2(20) NOT NULL,
    STUDENT_ID            VARCHAR2(20),
    COURSE_ID             VARCHAR2(20),
    ATTENDANCE_PERCENTAGE NUMBER(6,2),
    TOTAL_CLASSES         NUMBER(4),
    ATTENDED_CLASSES      NUMBER(4),
    CONSTRAINT PK_ATTENDANCE PRIMARY KEY (ATTENDANCE_ID),
    CONSTRAINT FK_ATTENDANCE_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (STUDENT_ID),
    CONSTRAINT FK_ATTENDANCE_COURSE FOREIGN KEY (COURSE_ID) REFERENCES COURSE (COURSE_ID)
);

-- TABLE 4: EXAM_RESULT
CREATE TABLE EXAM_RESULT (
    RESULT_ID        VARCHAR2(20) NOT NULL,
    STUDENT_ID       VARCHAR2(20),
    COURSE_ID        VARCHAR2(20),
    MARKS            NUMBER(6,2),
    MAX_MARKS        NUMBER(6,2),
    EXAM_DATE        DATE,
    CONSTRAINT PK_EXAM_RESULT PRIMARY KEY (RESULT_ID),
    CONSTRAINT FK_RESULT_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT (STUDENT_ID),
    CONSTRAINT FK_RESULT_COURSE FOREIGN KEY (COURSE_ID) REFERENCES COURSE (COURSE_ID)
);

-- Comments on Schema Architecture
COMMENT ON TABLE STUDENT IS 'Undergraduate and postgraduate students directory';
COMMENT ON TABLE COURSE IS 'Academic course catalog';
COMMENT ON TABLE ATTENDANCE IS 'Class attendance tracking per student and course';
COMMENT ON TABLE EXAM_RESULT IS 'Semester examinations score records';

